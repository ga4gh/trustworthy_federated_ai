# plot_results.py
"""
Reads isolated single-round metrics CSVs from MinIO (S3) generated by 
the stateless GA4GH TES federated learning execution.

Retrieves:
    s3://fl-checkpoints/metrics/server_metrics_round_*.csv
    s3://fl-checkpoints/metrics/fl_client_site_*_round_*.csv

Produces:
    results/fl_convergence_curve.png        Global and per-site accuracy & loss over rounds
"""

import os
import re
import boto3
import pandas as pd
import matplotlib.pyplot as plt
from io import BytesIO

# Configuration for local MinIO port-forwarded to host
MINIO_ENDPOINT = os.getenv("MINIO_ENDPOINT", "http://localhost:9000")
ACCESS_KEY = os.getenv("MINIO_ACCESS_KEY", "minioadmin")
SECRET_KEY = os.getenv("MINIO_SECRET_KEY", "minioadmin")
BUCKET = "fl-checkpoints"
METRICS_PREFIX = "metrics/"
RESULTS_DIR = os.path.join(os.path.dirname(__file__), "results")

def load_metrics_from_s3():
    """Connects to MinIO, finds all isolated round CSVs, and aggregates them."""
    s3 = boto3.client(
        's3',
        endpoint_url=MINIO_ENDPOINT,
        aws_access_key_id=ACCESS_KEY,
        aws_secret_access_key=SECRET_KEY
    )

    try:
        response = s3.list_objects_v2(Bucket=BUCKET, Prefix=METRICS_PREFIX)
        if 'Contents' not in response:
            print(f"[!] No metrics found in s3://{BUCKET}/{METRICS_PREFIX}")
            return pd.DataFrame(), {}
    except Exception as e:
        print(f"[!] Failed to connect to MinIO at {MINIO_ENDPOINT}: {e}")
        print("    -> Did you run the port-forward script? (kubectl port-forward svc/minio 9000:9000 -n fl-system)")
        return pd.DataFrame(), {}

    server_dfs = []
    client_dfs = {}

    for obj in response['Contents']:
        key = obj['Key']
        if not key.endswith('.csv'):
            continue

        # Download CSV directly into memory
        csv_obj = s3.get_object(Bucket=BUCKET, Key=key)
        df = pd.read_csv(BytesIO(csv_obj['Body'].read()))

        # Route the DataFrame to the correct list based on filename
        if "server_metrics" in key:
            server_dfs.append(df)
        elif "client_site" in key:
            # Extract site ID from filename (e.g., fl_client_site_1_round_5_metrics.csv)
            match = re.search(r'site_([A-Za-z0-9]+)_round', key)
            if match:
                site = match.group(1)
                if site not in client_dfs:
                    client_dfs[site] = []
                client_dfs[site].append(df)

    # Aggregate lists into unified master DataFrames and sort chronologically
    if server_dfs:
        server_master = pd.concat(server_dfs, ignore_index=True).sort_values(by='round')
    else:
        server_master = pd.DataFrame()

    client_master = {}
    for site, dfs in client_dfs.items():
        client_master[site] = pd.concat(dfs, ignore_index=True).sort_values(by='round')

    return server_master, client_master

def plot_convergence(server_df, client_dfs):
    """Plots the aggregated loss and accuracy metrics."""
    os.makedirs(RESULTS_DIR, exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(15, 6))

    # --- Plot 1: Accuracy ---
    if not server_df.empty and 'global_test_accuracy' in server_df.columns:
        axes[0].plot(server_df['round'], server_df['global_test_accuracy'],
                     marker='o', linewidth=2.5, label='Global Test (Server)', color='black')

    for site, df in client_dfs.items():
        if 'val_accuracy' in df.columns:
            axes[0].plot(df['round'], df['val_accuracy'], 
                         marker='x', linestyle='--', alpha=0.7, label=f'Site {site} Val')

    axes[0].set_title('Federated Convergence: Accuracy', fontsize=14)
    axes[0].set_xlabel('Communication Round', fontsize=12)
    axes[0].set_ylabel('Accuracy', fontsize=12)
    axes[0].grid(True, linestyle=':', alpha=0.6)
    axes[0].legend()

    # --- Plot 2: Loss ---
    if not server_df.empty and 'global_test_loss' in server_df.columns:
        axes[1].plot(server_df['round'], server_df['global_test_loss'],
                     marker='o', linewidth=2.5, label='Global Test (Server)', color='black')

    for site, df in client_dfs.items():
        if 'val_loss' in df.columns:
            axes[1].plot(df['round'], df['val_loss'], 
                         marker='x', linestyle='--', alpha=0.7, label=f'Site {site} Val')

    axes[1].set_title('Federated Convergence: Loss', fontsize=14)
    axes[1].set_xlabel('Communication Round', fontsize=12)
    axes[1].set_ylabel('Loss', fontsize=12)
    axes[1].grid(True, linestyle=':', alpha=0.6)
    axes[1].legend()

    plt.tight_layout()
    out_path = os.path.join(RESULTS_DIR, "fl_convergence_curve.png")
    fig.savefig(out_path, dpi=150)
    print(f"\n[✓] Convergence plot successfully generated: {out_path}")

def main():
    print("Fetching scattered stateless metrics from MinIO S3...")
    server_df, client_dfs = load_metrics_from_s3()

    if server_df.empty and not client_dfs:
        print("[!] No data to plot. Ensure the orchestrator has pushed metrics to S3.")
        return

    if not server_df.empty:
        print(f"[✓] Aggregated {len(server_df)} server rounds.")
    
    for site, df in client_dfs.items():
        print(f"[✓] Aggregated {len(df)} rounds for Site {site}.")

    plot_convergence(server_df, client_dfs)

if __name__ == "__main__":
    main()